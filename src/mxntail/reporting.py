def table_comparison(fc, cfg, num):
    models = cfg["forecast"]["models"]
    ev = cfg["evaluation"]
    losses = ["nls", "FZ95", "FZ99"]
    dm, mcs = comparison_table(fc, models, BENCH, losses, ev["hac_lags"], ev["mcs_size"],
                               ev["mcs_reps"], ev["mcs_block"], seed=cfg["forecast"]["seed"])
    dm.to_csv(results_dir() / "dm_main.csv", index=False)
    mcs.to_csv(results_dir() / "mcs_main.csv")
    means = fc.groupby("model")[losses].mean()
    rows = []
    for m in models:
        cells = [m]
        for loss in losses:
            if m == BENCH:
                cells += [f"{means.loc[m, loss]:.4f}", "--"]
            else:
                r = dm[(dm.loss == loss) & (dm.model == m)].iloc[0]
                cells += [f"{means.loc[m, loss]:.4f}", f"{r.t:+.2f}"]
            p = mcs.loc[m, loss]
            cells.append(("\\textbf{" + f"{p:.3f}" + "}") if p >= ev["mcs_size"] else f"{p:.3f}")
        rows.append(" & ".join(cells))
    _write_tex("tab_compare",
               r"Model & \multicolumn{3}{c}{Negative log score} & \multicolumn{3}{c}{FZ0 loss, 95\%} & "
               r"\multicolumn{3}{c}{FZ0 loss, 99\%} \\"
               r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}"
               r" & Mean & DM $t$ & MCS $p$ & Mean & DM $t$ & MCS $p$ & Mean & DM $t$ & MCS $p$",
               rows, "lrrrrrrrrr")
    for loss in losses:
        for m in models:
            num[f"mcs{_macro(loss)}{_macro(m)}"] = f"{mcs.loc[m, loss]:.3f}"
            if m != BENCH:
                r = dm[(dm.loss == loss) & (dm.model == m)].iloc[0]
                num[f"dmt{_macro(loss)}{_macro(m)}"] = f"{r.t:.2f}"
                num[f"dmp{_macro(loss)}{_macro(m)}"] = _p(r.p)
    return dm, mcs


def table_events(fc, cfg, num):
    models = cfg["forecast"]["models"]
    rows, recs = [], []
    for ev, (a, b) in EVENTS.items():
        g = fc[(fc.date >= a) & (fc.date <= b)]
        if g.empty:
            continue
        n = g[g.model == BENCH].shape[0]
        ymax = g[g.model == BENCH].y.max()
        cells = [ev, f"{n}", f"{ymax:.2f}"]
        for m in models:
            h = g[g.model == m]
            cells.append(f"{int(h.hit99.sum())}")
            recs.append({"event": ev, "model": m, "n": n, "max_return": ymax,
                         "exc99": int(h.hit99.sum()), "exc95": int(h.hit95.sum()),
                         "nls": h.nls.mean(), "fz99": h.FZ99.mean()})
        best = min(models, key=lambda m: g[g.model == m].nls.mean())
        cells.append(best)
        rows.append(" & ".join(cells))
    pd.DataFrame(recs).to_csv(results_dir() / "events_main.csv", index=False)
    short = SHORT
    hdr = "Episode & Days & Max $r_t$ & " + " & ".join(short[m] for m in models) + " & Best NLS"
    _write_tex("tab_events", hdr, rows, "p{0.24\\linewidth}rr" + "r" * len(models) + "l")


def table_robustness(cfg, num):
    models = cfg["forecast"]["models"]
    r = cfg["robustness"]
    variants = [("main", f"Rolling {cfg['forecast']['window']}, refit {cfg['forecast']['refit_every']}"),
                (f"window{r['alt_window']}", f"Rolling {r['alt_window']}, refit {cfg['forecast']['refit_every']}"),
                (f"refit{r['alt_refit_every']}", f"Rolling {cfg['forecast']['window']}, refit {r['alt_refit_every']}"),
                ("expanding1993", "Expanding from Nov 1993, refit 63")]
    rows, recs = [], []
    for tag, label in variants:
        path = results_dir() / f"forecasts_{tag}.csv.gz"
        if not path.exists():
            continue
        fc = load_forecasts(tag, cfg)
        s = summary_table(fc, models, cfg["forecast"]["alphas"]).set_index("model")
        best = s.NLS.idxmin()
        rows.append(f"\\multicolumn{{{len(models) + 1}}}{{l}}{{\\textit{{{label}}}}}")
        for stat, lab, fmt in [("NLS", "NLS", "{:.4f}"), ("exc99", "Exc. 99\\%", "{:d}"),
                               ("FZ99", "FZ0 99\\%", "{:.3f}")]:
            vals = [fmt.format(int(s.loc[m, stat]) if stat == "exc99" else s.loc[m, stat]) for m in models]
            if stat == "NLS":
                vals = [("\\textbf{" + v + "}") if m == best else v for m, v in zip(models, vals)]
            rows.append(f"\\quad {lab} & " + " & ".join(vals))
        for m in models:
            recs.append({"variant": tag, "model": m, **s.loc[m].to_dict()})
            num[f"robNls{_macro(tag)}{_macro(m)}"] = f"{s.loc[m, 'NLS']:.4f}"
            num[f"robExc{_macro(tag)}{_macro(m)}"] = f"{int(s.loc[m, 'exc99'])}"
            num[f"robPcc{_macro(tag)}{_macro(m)}"] = _p(s.loc[m, "p_cc99"])
        num[f"robBest{_macro(tag)}"] = best
        if tag == "expanding1993":
            for m in models:
                num[f"expNls{_macro(m)}"] = f"{s.loc[m, 'NLS']:.4f}"
                num[f"expExcNN{_macro(m)}"] = f"{int(s.loc[m, 'exc99'])}"
    pd.DataFrame(recs).to_csv(results_dir() / "robustness_summary.csv", index=False)
    short = SHORT
    _write_tex("tab_robust", " & " + " & ".join(short[m] for m in models), rows, "l" + "r" * len(models))


def table_montecarlo(cfg, num):
    path = results_dir() / "montecarlo_scores.csv"
    if not path.exists():
        return
    sc = pd.read_csv(path)
    models = cfg["forecast"]["models"]
    dgps = cfg["montecarlo"]["dgps"]
    rows, recs = [], []
    for dgp in dgps:
        g = sc[sc.dgp == dgp]
        wide = g.pivot(index="rep", columns="model", values="nls")[models]
        best = wide.mean().idxmin()
        cells = [dgp]
        for m in models:
            d = wide[m] - wide[dgp]
            se = d.std(ddof=1) / np.sqrt(len(d)) if m != dgp else np.nan
            txt = f"{wide[m].mean():.4f}"
            if m == best:
                txt = "\\textbf{" + txt + "}"
            cells.append(txt)
            recs.append({"dgp": dgp, "model": m, "mean_nls": wide[m].mean(),
                         "diff_vs_true": d.mean(), "mc_se": se,
                         "exc99": g[g.model == m].exc99.mean(), "exc95": g[g.model == m].exc95.mean(),
                         "share_best": float((wide.idxmin(axis=1) == m).mean())})
        rows.append(" & ".join(cells))
        ex = g.groupby("model").exc99.mean()[models]
        rows.append("\\quad 99\\% exc. (\\%) & " + " & ".join(f"{100 * v:.2f}" for v in ex))
        share = wide.idxmin(axis=1).value_counts(normalize=True).reindex(models).fillna(0)
        rows.append("\\quad Best NLS (\\%) & " + " & ".join(f"{100 * v:.0f}" for v in share))
        bic = g.pivot(index="rep", columns="model", values="bic")[models].idxmin(axis=1)
        bshare = bic.value_counts(normalize=True).reindex(models).fillna(0)
        for m in models:
            num[f"mcBic{_macro(dgp)}{_macro(m)}"] = f"{100 * bshare[m]:.0f}"
            num[f"mcExc{_macro(dgp)}{_macro(m)}"] = f"{100 * ex[m]:.2f}"
            num[f"mcNls{_macro(dgp)}{_macro(m)}"] = f"{wide[m].mean():.4f}"
        if dgp != dgps[-1]:
            rows.append("MIDRULE")
    out = pd.DataFrame(recs)
    out.to_csv(results_dir() / "montecarlo_summary.csv", index=False)
    short = SHORT
    _write_tex("tab_mc", "DGP & " + " & ".join(short[m] for m in models), rows, "l" + "r" * len(models))
    num["mcReps"] = f"{cfg['montecarlo']['replications']}"
    num["mcTrain"] = f"{cfg['montecarlo']['n_train']:,}"
    num["mcTest"] = f"{cfg['montecarlo']['n_test']}"
    o = out.set_index(["dgp", "model"])
    for dgp in dgps:
        for m in models:
            num[f"mcDiff{_macro(dgp)}{_macro(m)}"] = f"{o.loc[(dgp, m), 'diff_vs_true']:.4f}"
            num[f"mcShare{_macro(dgp)}{_macro(m)}"] = f"{100 * o.loc[(dgp, m), 'share_best']:.0f}"
    rec = pd.read_csv(results_dir() / "montecarlo_recovery.csv")
    g = rec[rec.dgp == "GARCH-Merton"]
    if len(g):
        for p in ["lambda", "muJ", "deltaJ"]:
            e = g[f"hat_{p}"] - g[f"true_{p}"]
            num[f"mcRmse{_macro(p)}"] = f"{np.sqrt(np.mean(e ** 2)):.3f}"
            num[f"mcLo{_macro(p)}"] = f"{g[f'hat_{p}'].quantile(0.05):.3f}"
            num[f"mcHi{_macro(p)}"] = f"{g[f'hat_{p}'].quantile(0.95):.3f}"
            num[f"mcBias{_macro(p)}"] = f"{e.mean():.3f}"
            num[f"mcTrue{_macro(p)}"] = f"{g[f'true_{p}'].iloc[0]:.3f}"


def table_application(fc, cfg, num):
    """Illustrative one-day FX risk of a Mexican importer with a USD payable."""
    models = cfg["forecast"]["models"]
    E = cfg["application"]["exposure_usd"]
    lv = returns(cfg)[["date", "usdmxn"]]
    prev = lv.set_index("date").usdmxn.shift(1)
    rows, recs = [], []
    for m in models:
        g = fc[fc.model == m].copy()
        s_prev = prev.reindex(g.date).to_numpy()
        conv = lambda r: E * s_prev * (np.exp(r / 100.0) - 1.0)
        loss, es99, var99 = conv(g.y.to_numpy()), conv(g.ES99.to_numpy()), conv(g.VaR99.to_numpy())
        hit = loss > var99
        shortfall = np.where(loss > es99, loss - es99, 0.0)
        recs.append({"model": m, "mean_es99_mxn": es99.mean(), "mean_var99_mxn": var99.mean(),
                     "breaches": int(hit.sum()), "mean_excess_on_breach": (loss - var99)[hit].mean(),
                     "total_shortfall_beyond_es": shortfall.sum()})
        r = recs[-1]
        rows.append(f"{m} & {r['mean_var99_mxn'] / 1e3:,.1f} & {r['mean_es99_mxn'] / 1e3:,.1f} & "
                    f"{r['breaches']} & {r['mean_excess_on_breach'] / 1e3:,.1f} & "
                    f"{r['total_shortfall_beyond_es'] / 1e3:,.0f}")
    pd.DataFrame(recs).to_csv(results_dir() / "application_main.csv", index=False)
    _write_tex("tab_app", r"Model & Mean VaR$_{99}$ & Mean ES$_{99}$ & Breaches & Mean excess & "
                          r"Shortfall beyond ES", rows, "lrrrrr")
    a = pd.DataFrame(recs).set_index("model")
    for m in models:
        num[f"appEs{_macro(m)}"] = f"{a.loc[m, 'mean_es99_mxn'] / 1e3:,.1f}"
        num[f"appShort{_macro(m)}"] = f"{a.loc[m, 'total_shortfall_beyond_es'] / 1e3:,.0f}"


