def _p(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def _f(v, d=3):
    return f"{v:.{d}f}"


def _write_tex(name, header, rows, colspec, caption=None, notes=None):
    """Write a booktabs tabular (the float and caption live in the .tex manuscript)."""
    lines = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    for r in rows:
        lines.append("\\midrule" if r == "MIDRULE" else r + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if notes:
        lines.append(f"\\par\\smallskip\\parbox{{\\linewidth}}{{\\footnotesize {notes}}}")
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / f"{name}.tex").write_text("\n".join(lines) + "\n")


class Numbers:
    """Collects \\newcommand macros for numbers quoted in the text."""

    def __init__(self):
        self.items = {}

    def __setitem__(self, k, v):
        self.items[k] = v

    def write(self):
        body = "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.items.items()))
        (PAPER / "numbers.tex").write_text("% Auto-generated by mxntail.reporting. Do not edit.\n" + body + "\n")


_DIGITS = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six",
                                   "Seven", "Eight", "Nine"]))


def _macro(s):
    """Model or loss name -> letters-only LaTeX macro fragment (FZ99 -> FzNineNine)."""
    return "".join(_DIGITS.get(ch, ch) for ch in s.title() if ch.isalnum())


